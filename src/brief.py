"""Generate docs/BRIEF.md — the plain-language read of the committed numbers.

The salience layer (docs/IMPACT.md, lever L4). The verified evidence-to-action finding is that
this project is credibility-rich and salience-poor: the honest numbers exist but only in a
register experts read. This module renders them in plain language WITHOUT inflating certainty —
the noise floor stays the headline (IMPACT.md red line 4), the forecast stays negative, and
nothing is claimed that the derived data does not contain.

Same contract as ledger_digest: deterministic (no clock, no volatile stamps — regenerating from
the same committed data is byte-identical), `--write` (re)generates, no args verifies and FAILS
if the committed file is stale. `make brief` wraps --write; the unit tests hold the freshness
gate, so `make dashboard` catches a stale brief without an eighth audit line.
"""
import argparse
import json
import os
import sys

REPO = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
DERIVED = os.path.join(REPO, "data", "derived")
OUT = os.path.join(REPO, "docs", "BRIEF.md")

# Grade order for the plain-language tally; noun-phrase glosses so any count reads correctly.
GRADE_LINE = (
    ("ROBUST", "held up under verification"),
    ("CONTESTED", "genuinely contested — real evidence on both sides"),
    ("REFUTED", "refuted — kept on the record"),
    ("OPEN", "open — the evidence cannot yet answer"),
)


def _load(name):
    with open(os.path.join(DERIVED, name), encoding="utf-8") as f:
        return json.load(f)


def _plural(n, word):
    if n == 1:
        return f"1 {word}"
    return f"{n} {word[:-1]}ies" if word.endswith("y") else f"{n} {word}s"


def build_brief(wgi, voice, forecast, index):
    """Pure: committed derived dicts -> the brief's markdown. No I/O, no clock."""
    o = wgi["overall"]
    va = wgi["dimensions"]["VA"]
    n_dims = len(wgi["dimensions"])
    cells = o["dimension_country_cells"]
    noise = o["within_noise"]
    noise_pct = round(noise / cells * 100)
    dec, imp = o["meaningful_declines"], o["meaningful_improvements"]
    concur = voice["counts"]["CONCUR-DECLINE"]
    concur_imp = voice["counts"]["CONCUR-IMPROVE"]
    conflicts = voice["counts"]["CONFLICT"]
    full_concur = voice["headline_concur_decline_n_sig_3"]
    # ISO3 -> display name from the committed per-country table, so the reader gets words not codes
    names = {c["country"]: c["country_name"] for c in voice["countries"]
             if "country" in c and "country_name" in c}
    concur_names = sorted(names.get(c, c) for c in full_concur)
    n_fc = forecast["result"]["n_forecasts"]
    grades = {g: 0 for g, _ in GRADE_LINE}
    for e in index["entries"]:
        grades[e["grade"]] = grades.get(e["grade"], 0) + 1
    total = len(index["entries"])
    window = f"{wgi['baseline_year']}–{wgi['latest_year']}"

    tally = " ".join(f"**{grades[g]}** {desc};" for g, desc in GRADE_LINE).rstrip(";")

    # the generated file's licence tag is split ({'-'}) so licence scanners don't read it as this file's
    return f"""<!--
SPDX-FileCopyrightText: 2026 The Pharos contributors
SPDX{'-'}License-Identifier: CC-BY-SA-4.0
-->

<!-- GENERATED by src/brief.py from the committed derived data — do not edit by hand.
     Regenerate with `make brief`; the unit tests fail if this file goes stale. -->

# The Pharos Brief — what the data says, in plain language

Everything below is computed from the committed, reproducible data in this repo — the same
numbers the machine gates pin, in a register anyone can read. Nothing here is a new claim;
it is the same honesty, translated.

## The one-sentence version

Most of the movement in governance scores over {window} is **statistical noise ({noise_pct}%
of what we measured)** — but where a real signal exists, decline outpaces improvement, it is
concentrated in **citizens' voice** (free expression, free media, participation), and on
{_plural(len(full_concur), "country")} all three instruments (overlapping, not independent) agree it is happening.

## The ledger, plainly

Of the **{total} claims** graded so far: {tally}. Every grade carries a pre-registered
"what would change our minds" — collected in the
[falsification watch](../ledger/INDEX.md). A claim that cannot be withdrawn is dogma;
ours can be, in public.

## The governance signal

Across **{cells:,} country-and-dimension measurements** ({window}, {n_dims} World Bank
governance dimensions, ~{cells // n_dims} countries): **{noise:,} ({noise_pct}%) moved less
than their own measurement error** — reported as noise, not news. Of the {dec + imp} real movements that remain,
**{dec} are declines and {imp} are improvements** ({o['decline_to_improve_ratio']}:1).
The imbalance is not spread evenly: in *Voice & Accountability* alone it is
**{va['counts']['DECLINE']} declines to {va['counts']['IMPROVE']} improvements**. In plain
terms: where governance is measurably changing, the space for citizens to speak, publish,
and participate is the part most often shrinking.

## Where the instruments agree

One index can be wrong; that is why we use three (World Bank, V-Dem, Freedom House) and
publish their **disagreements instead of averaging them away**. Over {window}: in
**{concur} countries** every instrument that registers a significant change agrees voice
declined — no instrument dissents ({concur_imp} show the mirror-image agreement on
improvement), and in **{conflicts} countries the instruments genuinely conflict** — those
are named, not blended. The highest-confidence set — decline significant on **all three**
instruments — is **{_plural(len(full_concur), "country")}**:

> {", ".join(concur_names)}.

## The forecast, honestly

We scored **{n_fc:,} pre-registered forecasts** of backsliding against the dumbest possible
baseline ("assume nothing changes"). Result: **our best model does not beat that baseline
yet** — and that finding is the product, published before any model was allowed to look
good. A forecast that grades itself in the open and reports a miss is doing its job; the
plain-language version of why is in
[the calibrated-miss explainer](forecast/CALIBRATED_MISS_EXPLAINER.md).

## Who this is for

- **A journalist** asking *"is this country's reported decline real, or noise?"* — check the
  [indicator table](indicators/wgi-governance.md) for the significance flag, and the
  [divergence table](indicators/voice-divergence.md) for whether the three instruments
  agree, before the story ships.
- **A watchdog or civil-society monitor** deciding *where scarce attention goes* — the
  {len(full_concur)}-country full-concurrence list above is the highest-confidence
  starting set; the {conflicts} conflict countries are where a single-source claim would
  mislead.
- **A researcher** asking *which claims are safe to build on* — the
  [graded ledger](../ledger/INDEX.md) states each claim's evidence and its falsification
  trigger; everything recomputes offline (`make verify-offline`).

---

*Regenerate: `make brief`. Verify everything yourself: [`docs/TRUST_SIGNALS.md`](TRUST_SIGNALS.md).
Country/institution level only — [watch power, not people](../THREAT_MODEL.md).*
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate/verify the plain-language brief (docs/BRIEF.md).")
    ap.add_argument("--write", action="store_true", help="(re)write docs/BRIEF.md from the derived data")
    args = ap.parse_args(argv)

    try:
        text = build_brief(_load("wgi_governance_summary.json"), _load("voice_divergence.json"),
                           _load("forecast_backtest.json"),
                           json.load(open(os.path.join(REPO, "ledger", "index.json"), encoding="utf-8")))
    except FileNotFoundError as e:
        print(f"brief: missing input {os.path.basename(e.filename or '?')} — run `make` to build the derived data")
        return 2

    if args.write:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"brief: wrote {os.path.relpath(OUT, REPO)}")
        return 0

    try:
        committed = open(OUT, encoding="utf-8").read()
    except FileNotFoundError:
        print("brief: docs/BRIEF.md missing — run `make brief`")
        return 1
    if committed != text:
        print("brief: STALE — docs/BRIEF.md does not match the derived data; run `make brief` and commit")
        return 1
    print("brief: ok — docs/BRIEF.md matches the committed derived data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
