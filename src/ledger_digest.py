"""Ledger digest — the human *read* surface + falsification watch, generated from the entries.

The ledger's write phase (adding entries) and its gates (`validate`, `staleness`) are covered;
this is the **read** phase of the ledger's *write → manage → read* cycle. It produces one browseable
`ledger/INDEX.md`: a by-grade index of every entry, plus a **falsification watch** — each entry's
pre-registered "what would change our minds" trigger in a single place. That watch is the asset
that separates a falsifiable ledger from advocacy.

It is generated from each entry's frontmatter (the source of truth), so it cannot silently drift:
`make index` (re)writes the file, and running this with no args **fails** if the committed file is
stale (wired into `make verify` / `verify-offline` / `dashboard`). Deterministic — the "next review"
date is `last_reviewed + interval`, computed without reading the clock, so the committed file is
reproducible and testable.

Pure core (`build_digest`) + thin CLI. Stdlib only.
"""
from __future__ import annotations

import argparse
import os
import sys
from datetime import timedelta

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ledger_staleness import last_reviewed, read_entries, review_interval  # noqa: E402

GRADE_ORDER = ("ROBUST", "CONTESTED", "REFUTED", "OPEN")
GRADE_MARK = {"ROBUST": "🟢", "CONTESTED": "🟡", "REFUTED": "🔴", "OPEN": "⚪"}


def _next_review(meta):
    """Deterministic next-review date: last_reviewed + interval (no clock — live status is
    `make staleness`)."""
    rev = last_reviewed(meta)
    return (rev + timedelta(days=review_interval(meta))).isoformat() if rev else "—"


def _cell(s):
    """Escape a table cell so a stray pipe in a title can't break the markdown table."""
    return str(s).replace("|", "\\|").strip()


def build_digest(entries):
    """Pure. ``entries`` is a list of ``(file, meta)``. Returns the INDEX.md markdown. O(n)."""
    by_grade = {}
    for file, meta in entries:
        by_grade.setdefault(meta.get("grade", "?"), []).append((file, meta))
    counts = {g: len(by_grade.get(g, [])) for g in GRADE_ORDER}
    total = len(entries)

    L = [
        "<!-- SPDX-FileCopyrightText: 2026 The Pharos contributors -->",
        # the generated file's licence tag, split so licence scanners don't read it as this file's
        "<!-- SPDX-" "License-Identifier: CC-BY-SA-4.0 -->",
        "<!-- GENERATED by `make index` (src/ledger_digest.py) from each entry's frontmatter. -->",
        "<!-- Do not edit by hand — edits are overwritten and the offline gate fails on drift. -->",
        "",
        "# Pharos Ledger — index & falsification watch",
        "",
        f"*{total} graded, falsifiable evidence entries — "
        + " · ".join(f"{counts[g]} {g}" for g in GRADE_ORDER)
        + ".* Every entry names, **up front, the condition under which it would be downgraded** — "
        "that is what separates this from advocacy. This view is regenerated from each entry's "
        "frontmatter (the source of truth) by `make index`.",
        "",
        "## By grade",
    ]
    for g in GRADE_ORDER:
        rows = sorted(by_grade.get(g, []), key=lambda fm: fm[1].get("id", ""))
        if not rows:
            continue
        L += [
            "",
            f"### {GRADE_MARK.get(g, '')} {g} ({len(rows)})",
            "",
            "| Entry | Claim | Domain | Verified | Next review |",
            "|---|---|---|---|---|",
        ]
        for file, meta in rows:
            L.append(
                f"| [{meta.get('id', '?')}]({file}) | {_cell(meta.get('title', '?'))} | "
                f"{_cell(meta.get('domain', '—'))} | {meta.get('verified', '—')} | {_next_review(meta)} |"
            )

    # Coverage by domain — where the evidence is concentrated, and (by thinness) where it is thin.
    domains = {}
    for _file, meta in entries:
        domains.setdefault(meta.get("domain", "—"), []).append(meta.get("grade", "?"))
    L += [
        "",
        "## Coverage by domain",
        "",
        "*Where the evidence sits — and, by its thinness, where the next entries belong.*",
        "",
        "| Domain | Entries | Grades |",
        "|---|---:|---|",
    ]
    for dom in sorted(domains, key=lambda d: (-len(domains[d]), d)):
        gs = domains[dom]
        L.append(
            f"| {_cell(dom)} | {len(gs)} | "
            + " · ".join(f"{gs.count(g)} {g}" for g in GRADE_ORDER if g in gs) + " |"
        )

    L += [
        "",
        "## Falsification watch — what would change our minds",
        "",
        "*The pre-registered trigger for every entry: meet one with evidence and the grade moves — "
        "in public, on the record. Live freshness is `make staleness`; re-grade cadence (CONTESTED "
        "270 d · OPEN 180 d · ROBUST/REFUTED 540 d) is in "
        "[`docs/GRADING_PROTOCOL.md`](../docs/GRADING_PROTOCOL.md).*",
        "",
    ]
    for file, meta in sorted(entries, key=lambda fm: fm[1].get("id", "")):
        trig = str(meta.get("falsification_trigger", "")).strip() or "*(no trigger recorded)*"
        L.append(
            f"- **[{meta.get('id', '?')}]({file})** · {meta.get('grade', '?')} · "
            f"*{_cell(meta.get('title', '?'))}* — {trig}"
        )
    L.append("")
    return "\n".join(L)


def _scan(ledger_dir):
    return read_entries(ledger_dir)  # the shared "what counts as an entry" rule


def _default_ledger_dir():
    return os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ledger"))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate/verify the ledger index + falsification watch.")
    ap.add_argument("--ledger", default=_default_ledger_dir())
    ap.add_argument("--write", action="store_true", help="(re)write ledger/INDEX.md from the entries")
    args = ap.parse_args(argv)

    digest = build_digest(_scan(args.ledger))
    index_path = os.path.join(args.ledger, "INDEX.md")

    if args.write:
        with open(index_path, "w", encoding="utf-8") as f:
            f.write(digest if digest.endswith("\n") else digest + "\n")
        print(f"wrote {os.path.relpath(index_path, os.path.dirname(args.ledger))}")
        return 0

    if not os.path.exists(index_path):
        print("FAIL: ledger/INDEX.md missing — run `make index`.")
        return 1
    with open(index_path, encoding="utf-8") as f:
        current = f.read()
    if current.rstrip("\n") != digest.rstrip("\n"):
        print("FAIL: ledger/INDEX.md is stale vs the entries — run `make index` and commit.")
        return 1
    print("ledger index: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
