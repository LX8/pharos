"""Generate docs/WATCH_REPORT.md — the flagship-edition prototype (docs/IMPACT.md lever L2).

The verified media/public mechanism (IMPACT.md claim 6, SUPPORTED) is a NAMED, single-object
artifact on a fixed cadence — the Doomsday Clock pattern. This prototypes that artifact from
the committed data so the machinery exists the day the founder decides the two things only
the founder can: the public name and the fixed date. The carryable single object is the
WATCH LIST — the countries where all three independent instruments concur, at significance,
that civic voice is declining.

Same contract as brief.py / ledger_digest.py: deterministic (no clock — the edition label
derives from the pinned data window), `--write` regenerates, no-args check fails when stale.
Symmetric by construction: no decline figure appears without its improvement counterpart
(the H3 rule of docs/BIAS_AUDIT_PREREGISTRATION.md).
"""
import argparse
import json
import os
import sys
from itertools import zip_longest

REPO = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
DERIVED = os.path.join(REPO, "data", "derived")
OUT = os.path.join(REPO, "docs", "WATCH_REPORT.md")


def _load(name):
    with open(os.path.join(DERIVED, name), encoding="utf-8") as f:
        return json.load(f)


def build_report(wgi, voice, forecast, index):
    """Pure: committed derived dicts -> the edition markdown. No I/O, no clock."""
    o = wgi["overall"]
    va = wgi["dimensions"]["VA"]
    cells, noise = o["dimension_country_cells"], o["within_noise"]
    noise_pct = round(noise / cells * 100)
    names = {c["country"]: c["country_name"] for c in voice["countries"]
             if "country" in c and "country_name" in c}
    watch = sorted(names.get(c, c) for c in voice["headline_concur_decline_n_sig_3"])
    # the improvement counterpart at the SAME bar as the Watch List (all three instruments
    # significant) — computed from the per-country table; the top-level CONCUR-IMPROVE count
    # is the looser >=2-significant set and must never be presented as this one's equal
    improve_full3 = sum(1 for c in voice["countries"]
                        if c["agreement"]["label"] == "CONCUR-IMPROVE" and c["agreement"]["n_sig"] == 3)
    concur_decline = voice["counts"]["CONCUR-DECLINE"]
    concur_improve = voice["counts"]["CONCUR-IMPROVE"]
    conflicts = voice["counts"]["CONFLICT"]
    grades = {}
    for e in index["entries"]:
        grades[e["grade"]] = grades.get(e["grade"], 0) + 1
    window = f"{wgi['baseline_year']}–{wgi['latest_year']}"

    # the generated file's licence tag is split ({'-'}) so licence scanners don't read it as this file's
    return f"""<!--
SPDX-FileCopyrightText: 2026 The Pharos contributors
SPDX{'-'}License-Identifier: CC-BY-SA-4.0
-->

<!-- GENERATED by src/watch_report.py from the committed derived data — do not edit by hand.
     Regenerate with `make watch-report`; the unit tests fail if this file goes stale. -->

# ⚠ PROTOTYPE — The Watch Report · data window {window}

> **Prototype edition (0).** The flagship's two public-facing decisions are the founder's
> and remain open: the **name** of the report and the **fixed annual date** it is issued
> (docs/IMPACT.md §6, lever L2). Everything else — the artifact's shape, its single
> carryable object, and its drift-gated generation — is built and working below.

## The Watch List — {len(watch)} countries

The one object this report exists to carry: the countries where **all three independent
instruments** (World Bank, V-Dem, Freedom House) **concur, each at its own significance
bar, that civic voice declined** over {window}. Not a score, not a blend — a concurrence.

> {", ".join(watch)}.

For balance, at the **same bar**: **{improve_full3} countries** show full three-instrument
concurrence on *improvement*. At the looser every-significant-instrument-agrees bar the
split is {concur_decline} declining to {concur_improve} improving, and in
**{conflicts} countries the instruments conflict** — those are named in the
[divergence table](indicators/voice-divergence.md), never averaged away.

## The state of the signal

- **{noise_pct}% of everything we measured is statistical noise** ({noise:,} of {cells:,}
  country×dimension changes, 90% CI) — the report's own noise floor comes first.
- Among real movements: **{o['meaningful_declines']} declines vs
  {o['meaningful_improvements']} improvements** ({o['decline_to_improve_ratio']}:1),
  concentrated in *Voice & Accountability* ({va['counts']['DECLINE']} vs
  {va['counts']['IMPROVE']}).
- The evidence ledger stands at **{len(index['entries'])} graded claims**
  ({grades.get('ROBUST', 0)} ROBUST · {grades.get('CONTESTED', 0)} CONTESTED ·
  {grades.get('REFUTED', 0)} REFUTED · {grades.get('OPEN', 0)} OPEN), every one carrying a
  pre-registered [falsification trigger](../ledger/INDEX.md).
- The forecast layer reports its own result honestly: **it does not yet beat a no-change
  baseline** ([why that is the product](forecast/pharos-forecast-v0.md)).

## Biggest measured movements (Voice & Accountability, {window})

Declines and improvements, side by side — this report never publishes one without the other.

| Largest declines | Δ score | z | | Largest improvements | Δ score | z |
|---|---|---|---|---|---|---|
{_zip_movers(va['top_declines'], va['top_improvements'])}

## What would change this report

Every claim above is falsifiable: the triggers are collected in the
[falsification watch](../ledger/INDEX.md), the data pin is checked against the live world
by `make drift`, and the whole edition regenerates byte-for-byte from committed data
(`make verify-offline`). If the next data pin moves a country on or off the Watch List,
the next edition says so — in public, with the numbers.

---

*Country/institution level only — [watch power, not people](../THREAT_MODEL.md). Verify
everything: [`docs/TRUST_SIGNALS.md`](TRUST_SIGNALS.md). Reuse the data:
[`docs/DATA_CONTRACT.md`](DATA_CONTRACT.md).*
"""


def _mover_cell(m):
    # a missing side (if the two top-N lists ever differ in length) prints a blank cell rather
    # than silently dropping the whole row — this report never lets asymmetry hide by truncation
    if m is None:
        return "— |  |"
    return f"{m['country']} | {m['change']:+.1f} | {m['z']:+.1f}"


def _zip_movers(declines, improvements):
    # zip_longest, not zip: zip would truncate to the shorter side and quietly under-report movements
    return "\n".join(f"| {_mover_cell(d)} | | {_mover_cell(i)} |"
                     for d, i in zip_longest(declines, improvements))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate/verify the flagship watch-report prototype.")
    ap.add_argument("--write", action="store_true", help="(re)write docs/WATCH_REPORT.md")
    args = ap.parse_args(argv)

    try:
        text = build_report(_load("wgi_governance_summary.json"), _load("voice_divergence.json"),
                            _load("forecast_backtest.json"),
                            json.load(open(os.path.join(REPO, "ledger", "index.json"), encoding="utf-8")))
    except FileNotFoundError as e:
        print(f"watch-report: missing input {os.path.basename(e.filename or '?')} — run `make` first")
        return 2

    if args.write:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"watch-report: wrote {os.path.relpath(OUT, REPO)}")
        return 0
    try:
        committed = open(OUT, encoding="utf-8").read()
    except FileNotFoundError:
        print("watch-report: docs/WATCH_REPORT.md missing — run `make watch-report`")
        return 1
    if committed != text:
        print("watch-report: STALE — run `make watch-report` and commit")
        return 1
    print("watch-report: ok — matches the committed derived data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
