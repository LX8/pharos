"""Structural integrity checks for the static site — the markup half of "every public
surface machine-checked".

The counts/figure gates already pin the site's *numbers* to the data; these pin its
*structure*: every class used in the HTML has a CSS rule (a missing one shipped once — the
OPEN grade pill), in-page anchors resolve, external links are https-only, accessibility
attributes are present, and the pure-HTML disclosure controls stay balanced.

The landing page is published in four languages, all generated by src/build_site.py from one
template (site/template.html) and per-language strings (site/i18n/). Every structural check
runs on every page; the translation checks pin that the committed pages ARE that build, and
that a translation cannot change what the English page states — its figures, links, commands
and language metadata. Stdlib only.
"""
import copy
import os
import re
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
import build_site  # noqa: E402

REPO = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))


def _read(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8") as f:
        return f.read()


PAGE_PATHS = build_site.page_paths()
PAGES = {rel: _read(os.path.join("site", rel)) for rel in PAGE_PATHS}
HTML = PAGES["index.html"]
CSS = _read("site/style.css")
TEMPLATE = _read("site/template.html")


def _strings():
    return {code: build_site.load_strings(REPO, code) for code, *_ in build_site.LANGS}


class TestSiteIntegrity(unittest.TestCase):
    def test_every_class_has_a_css_rule(self):
        # dead markup / typo'd class names render silently unstyled — catch them, on every page
        defined = set(re.findall(r"\.([A-Za-z][\w-]*)", CSS))
        for rel, html in PAGES.items():
            used = set()
            for blob in re.findall(r'class="([^"]+)"', html):
                used.update(blob.split())
            self.assertEqual(sorted(used - defined), [],
                             f"class used in site/{rel} with no rule in style.css")

    def test_inpage_anchors_resolve(self):
        for rel, html in PAGES.items():
            anchors = set(re.findall(r'href="#([^"]+)"', html))
            ids = set(re.findall(r'id="([^"]+)"', html))
            self.assertEqual(sorted(anchors - ids), [], f"site/{rel}: in-page anchor with no matching id")

    def test_external_links_are_https(self):
        for rel, html in PAGES.items():
            self.assertEqual(re.findall(r'href="http://[^"]*"', html), [],
                             f"site/{rel}: external link over plain http")

    def test_role_img_has_aria_label(self):
        for rel, html in PAGES.items():
            self.assertEqual(re.findall(r'role="img"(?![^>]*aria-label)', html), [],
                             f"site/{rel}: role=img without an aria-label")

    def test_disclosure_controls_balanced(self):
        for rel, html in PAGES.items():
            self.assertEqual(html.count("<details"), html.count("</details>"), rel)
            self.assertEqual(html.count("<summary"), html.count("</summary>"), rel)
            self.assertEqual(html.count("<details"), html.count("<summary"),
                             f"site/{rel}: every <details> fold needs its <summary> control")

    def test_skip_link_outranks_sticky_chrome(self):
        """The focused skip link must paint above any top-edge sticky chrome, or the page's
        primary keyboard affordance could be hidden. CORRECTION: this test's original
        docstring claimed the sticky nav had actually covered the skip link; independent
        verification showed that regression was impossible (absolute-at-top vs sticky-below-
        hero never overlap). The invariant is kept as a forward guard — future sticky chrome
        pinned to the top edge WOULD collide — but no real regression ever shipped.
        The guard discovers sticky rules from the stylesheet itself, so chrome added later
        (a toolbar, a banner) is covered without editing this test."""
        def zvalue(body):
            m = re.search(r"z-index:\s*(\d+)", body)
            return int(m.group(1)) if m else 0
        skip = re.search(r"\.skip\s*\{([^{}]*)\}", CSS)
        self.assertIsNotNone(skip, "no rule for .skip")
        # leaf rule blocks only (bodies without braces), so rules inside @media are seen too
        sticky = [(sel.strip(), zvalue(body))
                  for selectors, body in re.findall(r"([^{}]+)\{([^{}]*)\}", CSS)
                  if re.search(r"position:\s*sticky", body)
                  for sel in selectors.split(",")]
        self.assertTrue(sticky, "expected at least one sticky rule (the section nav)")
        for sel, z in sticky:
            self.assertGreater(zvalue(skip.group(1)), z,
                               f".skip must stack above sticky {sel} or focusing it is invisible")

    def test_grade_pills_cover_the_vocabulary(self):
        # the legend must style all four grades (the OPEN pill was once missing)
        for g in ("g-robust", "g-contested", "g-refuted", "g-open"):
            self.assertIn(f".{g}", CSS, f"grade pill .{g} has no CSS rule")


class TestTranslations(unittest.TestCase):
    """The four pages are one build; a translation changes the words, never what they point at."""

    def test_committed_pages_match_a_fresh_build(self):
        # the drift gate: a hand-edited page, or a template/strings/data change without
        # `make pages`, fails the suite (and therefore the dashboard and the Pages deploy)
        built = build_site.build_all(REPO)
        self.assertEqual(sorted(built), sorted(PAGE_PATHS))
        for rel, html in built.items():
            self.assertEqual(PAGES[rel], html, f"site/{rel} is stale — run `make pages` and commit")

    def test_build_is_deterministic(self):
        self.assertEqual(build_site.build_all(REPO), build_site.build_all(REPO))

    def test_no_placeholder_leaks(self):
        for rel, html in PAGES.items():
            self.assertNotRegex(html, r"\{\{|\}\}", f"site/{rel}: an unrendered placeholder")

    def test_language_metadata(self):
        langs = sorted([html_lang for _c, html_lang, *_ in build_site.LANGS] + ["x-default"])
        for _code, html_lang, og_locale, _name, rel in build_site.LANGS:
            html = PAGES[rel]
            url = build_site.BASE_URL + rel[:-len("index.html")]
            self.assertIn(f'<html lang="{html_lang}">', html, rel)
            self.assertIn(f'<link rel="canonical" href="{url}">', html, rel)
            self.assertIn(f'<meta property="og:url" content="{url}">', html, rel)
            self.assertIn(f'<meta property="og:locale" content="{og_locale}">', html, rel)
            # every page names every language (itself included) plus x-default — reciprocal hreflang
            alts = re.findall(r'<link rel="alternate" hreflang="([^"]+)" href="([^"]+)">', html)
            self.assertEqual(sorted(h for h, _ in alts), langs, rel)
            # the switcher marks exactly one link as the current page: this one
            current = re.findall(r'<a href="[^"]*" hreflang="([^"]+)" lang="[^"]+" aria-current="page">', html)
            self.assertEqual(current, [html_lang], rel)

    def test_relative_links_resolve(self):
        # the switcher and the stylesheet are relative paths; each must land on a published file
        site = os.path.realpath(os.path.join(REPO, "site"))
        for rel, html in PAGES.items():
            base = os.path.dirname(os.path.join(REPO, "site", rel))
            for href in re.findall(r'href="([^"#:]+)"', html):   # no anchors, no absolute URLs
                target = os.path.normpath(os.path.join(base, href))
                if href.endswith("/") or os.path.isdir(target):
                    target = os.path.join(target, "index.html")
                self.assertTrue(os.path.isfile(target), f"site/{rel}: {href!r} resolves to nothing")
                self.assertTrue(os.path.realpath(target).startswith(site + os.sep),
                                f"site/{rel}: {href!r} leaves the published site")

    def test_parity_check_bites(self):
        # a translation that changes a number, a link, a command or drops a live figure must fail
        strings = _strings()
        build_site.check_parity(strings)   # clean today
        mutations = (
            ("evidence_p2", lambda s: s.replace("95", "99")),
            ("path_read_p", lambda s: s.replace("{{url_brief}}", "https://example.org/")),
            ("step_serve", lambda s: s.replace("serve</code>", "start</code>", 1)),
            ("lede", lambda s: s.replace("{{within_noise_pct}}", "88")),
        )
        for key, mutate in mutations:
            bad = copy.deepcopy(strings)
            bad["de"][key] = mutate(bad["de"][key])
            self.assertNotEqual(bad["de"][key], strings["de"][key], f"the {key} mutation did not apply")
            with self.assertRaises(ValueError, msg=key):
                build_site.check_parity(bad)

    def test_key_drift_fails_the_build(self):
        strings = _strings()
        reserved = set(build_site.URLS) | set(build_site.figures(REPO)) | set(build_site.PAGE_KEYS)
        build_site.check_strings(TEMPLATE, strings, reserved)   # clean today
        missing = copy.deepcopy(strings)
        del missing["pt"]["lede"]                                # a translation lost a paragraph
        typo = copy.deepcopy(strings)
        typo["es"]["ledee"] = typo["es"].pop("lede")             # a misspelt key
        unused = copy.deepcopy(strings)
        shadow = copy.deepcopy(strings)
        for table in unused.values():
            table["orphan_paragraph"] = "never rendered"         # a key no page uses
        for table in shadow.values():
            table["version"] = "9.9.9"                           # a key that would hide a computed value
        for bad in (missing, typo, unused, shadow):
            with self.assertRaises(KeyError):
                build_site.check_strings(TEMPLATE, bad, reserved)

    def test_download_is_one_click_on_every_page(self):
        # the whole project must be downloadable straight from the page, in every language: the
        # hero button, the download panel, the how-to step and the footer all point at the ZIP
        zip_url = build_site.URLS["url_zip"]
        self.assertTrue(zip_url.startswith("https://github.com/LX8/pharos/archive/") and zip_url.endswith(".zip"))
        for rel, html in PAGES.items():
            self.assertGreaterEqual(html.count(f'href="{zip_url}"'), 4, f"site/{rel}: a download link is missing")
            self.assertIn('id="download"', html, f"site/{rel}: the download panel is missing")

    def test_pages_workflow_publishes_every_page(self):
        # adding a language must also publish it — and the deploy must run the freshness gate
        wf = _read(".github/workflows/pages.yml")
        self.assertIn("python3 src/build_site.py --list", wf, "the deploy must stage the generated page list")
        self.assertRegex(wf, r"(?m)^\s+python3 src/build_site\.py\s*$", "the gate must verify the pages are fresh")
        for rel in PAGE_PATHS:
            self.assertIn(f"'site/{rel}'", wf, f"the pages.yml paths filter misses site/{rel}")


if __name__ == "__main__":
    unittest.main()
